IF OBJECT_ID('LenhGiaoNhan','U') IS NULL
CREATE TABLE LenhGiaoNhan (
  MaLenh INT IDENTITY PRIMARY KEY,
  SoLenh NVARCHAR(20) NOT NULL,
  LoaiLenh NVARCHAR(20) NOT NULL,
  MaKH INT NULL,
  SoCont NVARCHAR(11) NULL,
  BienSoXe NVARCHAR(15) NOT NULL,
  TenTaiXe NVARCHAR(100) NULL,
  SdtTaiXe NVARCHAR(20) NULL,
  HenTuLuc DATETIME NOT NULL,
  HenDenLuc DATETIME NOT NULL,
  MaPin NVARCHAR(8) NOT NULL,
  TrangThai NVARCHAR(20) NOT NULL DEFAULT N'Chờ xe',
  GhiChu NVARCHAR(300) NULL,
  NgayTao DATETIME NOT NULL DEFAULT GETDATE(),
  VaoCongLuc DATETIME NULL,
  HoanTatLuc DATETIME NULL
);
GO
IF OBJECT_ID('PhieuCan','U') IS NULL
CREATE TABLE PhieuCan (
  MaPC INT IDENTITY PRIMARY KEY,
  SoPhieu NVARCHAR(20) NOT NULL,
  MaLenh INT NULL,
  BienSoXe NVARCHAR(15) NOT NULL,
  SoCont NVARCHAR(11) NULL,
  CanLan1 DECIMAL(10,1) NOT NULL,
  CanLan2 DECIMAL(10,1) NULL,
  Luc1 DATETIME NOT NULL DEFAULT GETDATE(),
  Luc2 DATETIME NULL,
  NguoiCan NVARCHAR(50) NULL,
  GhiChu NVARCHAR(200) NULL
);
GO
IF OBJECT_ID('ChungTu','U') IS NULL
CREATE TABLE ChungTu (
  MaCT INT IDENTITY PRIMARY KEY,
  SoChungTu NVARCHAR(30) NOT NULL,
  LoaiCT NVARCHAR(20) NOT NULL,
  SoCont NVARCHAR(11) NULL,
  MaKH INT NULL,
  BienSoXe NVARCHAR(15) NULL,
  MoTa NVARCHAR(300) NULL,
  LienKet NVARCHAR(200) NULL,
  NguoiLap NVARCHAR(50) NULL,
  NgayLap DATETIME NOT NULL DEFAULT GETDATE()
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_Lenh_Bien' AND object_id = OBJECT_ID('LenhGiaoNhan'))
    CREATE INDEX IX_Lenh_Bien ON LenhGiaoNhan(BienSoXe, TrangThai);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_CT_Cont' AND object_id = OBJECT_ID('ChungTu'))
    CREATE INDEX IX_CT_Cont ON ChungTu(SoCont);
GO
